print(2 + 3)  # 输出整数2和3的和，即5
print(2 - 3)  # 输出整数2和3的差，即-1
print(2 * 3)  # 输出整数2和3的积，即6
print(2 / 3)  # 输出整数2和3的商，即0.6666666666666666
print(2 // 3)  # 输出整数2和3的整除商，即0
print(2 % 3)  # 输出整数2和3的余数，即2
# -----------------------------------------------------------------------------------
#========================================NEW========================================
# 运算顺序
print((2 + 3) * 4)  # 输出(2 + 3) * 4，即20
print(2 + 3 * 4)  # 输出2 + 3 * 4，即14
# -----------------------------------------------------------------------------------
# 幂运算
print(2 * 2 * 2)  # 输出2的3次幂，即8
print(2 ** 3)  # 输出2的3次幂，即8
# -----------------------------------------------------------------------------------
# 负数运算
print(-2 + 3)  # 输出-2和3的和，即1
print(-2 - 3)  # 输出-2和3的差，即-5
print(-2 * 3)  # 输出-2和3的积，即-6
print(-2 / 3)  # 输出-2和3的商，即-0.6666666666666666
# -----------------------------------------------------------------------------------
# 自增和自减
x = 5
x += 1  # 等价于 x = x + 1
print(x)  # 输出6
x -= 1  # 等价于 x = x - 1
print(x)  # 输出5
# -----------------------------------------------------------------------------------
# 非常大和非常小
print(1e10)  # 输出10的10次幂，即10000000000.0
print(1e-10)  # 输出10的-10次幂，即1e-10
# -----------------------------------------------------------------------------------